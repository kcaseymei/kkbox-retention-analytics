"""Build the data file for the public dashboard (docs/index.html).

Reads only the aggregated result tables committed under reports/ and writes
docs/assets/dashboard_data.js. No user-level rows are published.

    python src/build_dashboard.py
"""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
REPORTS = ROOT / "reports"
OUT = ROOT / "docs" / "assets" / "dashboard_data.js"

TEST_MONTHS = ["2017-01", "2017-02", "2017-03"]
RECALL_MODELS = ["gradient boosting", "logistic regression", "rule: no auto-renew"]
BANDS = ["1-7", "8-14", "15-21", "22-31"]
GROUPS = ["stopped (0 days in the last 30)", "declined (more than 25%)",
          "stable (within 25%)", "increased (more than 25%)"]


def r(x, n=4):
    return None if pd.isna(x) else round(float(x), n)


def monthly():
    df = pd.read_csv(REPORTS / "signal_analysis" / "renewal_mode_by_month.csv")
    share = df["manual_share_of_users"] / 100
    df["churn_rate"] = share * df["churn_rate_manual"] + (1 - share) * df["churn_rate_auto"]
    cols = ["target_month", "label_source", "users", "churn_rate", "churn_rate_manual",
            "churn_rate_auto", "manual_share_of_users", "manual_share_of_churners"]
    return [{k: (r(v, 3) if isinstance(v, float) else v) for k, v in row.items()}
            for row in df[cols].to_dict("records")]


def recall():
    df = pd.read_csv(REPORTS / "model_results" / "results.csv")
    df = df[df["month"].isin(TEST_MONTHS) & df["model"].isin(RECALL_MODELS)]
    return [{"month": m, "split": s, "model": mo, "capacity": r(c), "recall": r(rc),
             "precision": r(p), "auc": r(a), "base_rate": r(b)}
            for m, s, mo, c, rc, p, a, b in df[["month", "split", "model", "capacity", "recall",
                                               "precision", "auc", "base_rate"]].itertuples(index=False)]


def stability():
    """Recall at 10% capacity on every validation and test month (model monitoring view)."""
    df = pd.read_csv(REPORTS / "model_results" / "results.csv")
    df = df[df["split"].isin(["validation", "test"]) & (df["capacity"] == 0.1)
            & df["model"].isin(["gradient boosting", "rule: no auto-renew"])]
    return [{"month": m, "split": s, "model": mo, "recall": r(rc), "precision": r(p), "auc": r(a)}
            for m, s, mo, rc, p, a in df[["month", "split", "model", "recall", "precision",
                                          "auc"]].itertuples(index=False)]


def decline_by_month():
    df = pd.read_csv(REPORTS / "signal_analysis" / "decline_by_month.csv")
    df = df.rename(columns={"share_stopped (0 days in the last 30)": "share_stopped",
                            "share_declined (more than 25%)": "share_declined",
                            "risk_ratio_fell_or_stopped_vs_stable": "risk_ratio"})
    cols = ["target_month", "label_source", "comparable_users", "share_stopped", "share_declined", "risk_ratio"]
    return [{k: (r(v, 3) if isinstance(v, float) else v) for k, v in row.items()}
            for row in df[cols].to_dict("records")]


def lead_time():
    df = pd.read_csv(REPORTS / "model_results" / "lead_time_bands.csv")
    df = df[df["band"].isin(BANDS) & df["model"].isin(["gradient boosting", "rule: no auto-renew"])]
    return [{"month": m, "model": mo, "band": b, "users": int(u), "recall": r(rc), "base_rate": r(br)}
            for m, mo, b, u, rc, br in df[["month", "model", "band", "users", "recall",
                                           "base_rate"]].itertuples(index=False)]


def decline_by_mode():
    df = pd.read_csv(REPORTS / "signal_analysis" / "decline_by_renewal_mode_test_months.csv")
    return [{"renewal_mode": m, "group": g, "users": int(u), "churn_rate": r(c, 3)}
            for m, g, u, c in df.itertuples(index=False) if g in GROUPS]


def importance(top=10):
    df = pd.read_csv(REPORTS / "model_results" / "feature_importance_2017-01.csv")
    df = df.sort_values("auc_drop", ascending=False).head(top)
    return [{"feature": f, "auc_drop": r(d, 5)} for f, d in df.itertuples(index=False)]


def main():
    data = {"monthly": monthly(), "recall": recall(), "stability": stability(),
            "lead_time": lead_time(), "decline_by_mode": decline_by_mode(),
            "decline_by_month": decline_by_month(), "importance": importance()}
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("// Generated by src/build_dashboard.py from reports/. Do not edit.\n"
                   "window.DASHBOARD_DATA = " + json.dumps(data, indent=1) + ";\n")
    print(f"wrote {OUT.relative_to(ROOT)}: " + ", ".join(f"{k}={len(v)}" for k, v in data.items()))


if __name__ == "__main__":
    main()
